import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';

const idx = JSON.parse(await readFile('.cache/spine-index.json', 'utf8'));
const enemy = JSON.parse(await readFile('.cache/enemy-spine-index.json', 'utf8'));
const ops = {};
for (const [id, v] of Object.entries(idx)) {
  const base = v.file.split('/').pop();
  const dir = `build/app/assets/spine/operators/${id}`;
  if (existsSync(`${dir}/${base}.skel`) && existsSync(`${dir}/${base}.atlas`) && existsSync(`${dir}/${base}.png`)) {
    ops[id] = { base: `assets/spine/operators/${id}/${base}`, name: v.name };
  }
}
const js = `// Generated by tools/build-spine-index.mjs.\nexport const SPINE_OPERATORS = ${JSON.stringify(ops, null, 2)};\nexport const SPINE_ENEMIES = ${JSON.stringify(enemy, null, 2)};\n`;
await writeFile('build/app/js/spine-index.js', js);
console.log('operator spine', Object.keys(ops).length, 'enemy spine', Object.keys(enemy).length);
