import { readFile, writeFile } from 'node:fs/promises';
const all = JSON.parse(await readFile('.cache/spine38-all.json', 'utf8')).found;
const old = JSON.parse(await readFile('.cache/spine-index.json', 'utf8'));
const ops = {};
for (const e of all) {
  const base = e.base.split('/').pop();
  ops[e.id] = { base: `assets/spine38/operators/${e.id}/${base}`, name: e.name };
}
const only35 = {};
for (const [id, v] of Object.entries(old)) {
  if (!ops[id]) {
    const base = v.file.split('/').pop();
    only35[id] = { base: `assets/spine/operators/${id}/${base}`, name: v.name };
  }
}
const js = `// Generated by tools/build-spine-index.mjs.\nexport const SPINE38_OPERATORS = ${JSON.stringify(ops, null, 2)};\nexport const SPINE35_ONLY = ${JSON.stringify(only35, null, 2)};\n`;
await writeFile('build/app/js/spine38-index.js', js);
console.log('spine38', Object.keys(ops).length, 'spine35-only', Object.keys(only35).length);
