import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { OPERATORS as OLD, STARTERS as OLD_STARTERS } from './operators.mjs';
import { STAGES as OLD_STAGES } from '../build/app/js/data.js';

const ops = JSON.parse(await readFile('.cache/all-operators.json', 'utf8'))
  .filter(o => !/卫戍协议/.test(o.name));
const opIds = new Set(ops.map(o => o.id));
const skins = JSON.parse(await readFile('.cache/all-skins.json', 'utf8'))
  .filter(s => opIds.has(s.opId));
const stageTitles = JSON.parse(await readFile('.cache/stage-titles.json', 'utf8'));

const skillTypes = { 先锋: 'buff', 近卫: 'aoe', 重装: 'shield', 狙击: 'multi', 术师: 'aoe', 医疗: 'heal', 辅助: 'buff', 特种: 'control' };
const powers = { 6: 2.8, 5: 2.2, 4: 1.9, 3: 1.6, 2: 1.4 };
for (const o of ops) {
  if (!o.skill || !o.skill.type) {
    const type = skillTypes[o.cls] || 'nuke';
    o.skill = {
      name: o.skill?.name || '战术指令', type,
      power: type === 'heal' ? Math.max(1.2, powers[o.rarity] * 0.72) : powers[o.rarity],
      ...(type === 'shield' ? { duration: 6 } : {}),
      ...(type === 'control' ? { duration: 2 } : {}),
      ...(type === 'buff' ? { duration: 8 } : {}),
      ...(type === 'multi' ? { hits: o.rarity >= 6 ? 5 : o.rarity >= 5 ? 4 : 3 } : {}),
      ...(o.cls === '医疗' ? { desc: `自动释放${o.skill?.name || '治疗指令'}，为全队回复生命。` } : {}),
    };
  }
  o.img = `assets/operators/${o.id}.webp`;
  if (!o.talent) o.talent = { name: `${o.cls}战术`, desc: `与${o.cls}职业特性联动的被动效果。` };
  if (!o.quote) o.quote = '博士，请下达指令。';
  // 旧 86 名保留手工技能；其余新干员按职业模板。
  const old = OLD.find(x => x.id === o.id);
  if (old?.skill) o.skill = old.skill;
  if (old?.talent) o.talent = old.talent;
  if (old?.quote) o.quote = old.quote;
}

for (const o of ops) {
  if (!existsSync(`build/app/assets/operators/${o.id}.webp`)) o.img = 'assets/operators/_placeholder.webp';
}
const jsOps = `// Generated by tools/build-v2-data.mjs. ${ops.length} operators.\nexport const OPERATORS = ${JSON.stringify(ops, null, 2)};\n\nexport const STARTERS = ${JSON.stringify(OLD_STARTERS)};\nexport const LIMITED_IDS = ${JSON.stringify(ops.filter(o => o.limited || o.collab).map(o => o.id))};\n`;
await writeFile('build/app/js/operators.js', jsOps);

const opImg = new Map(ops.map(o => [o.id, o.img]));
for (const s of skins) {
  s.price = 18;
  s.img = existsSync(`build/app/assets/skins/${s.id}.webp`) ? `assets/skins/${s.id}.webp` : opImg.get(s.opId) || 'assets/operators/_placeholder.webp';
}
const byOp = {};
for (const s of skins) (byOp[s.opId] ||= []).push(s);
const jsSkins = `// Generated by tools/build-v2-data.mjs. ${skins.length} skins.\nexport const SKINS = ${JSON.stringify(skins, null, 2)};\nexport const SKIN_BY_ID = new Map(SKINS.map(s => [s.id, s]));\nexport const SKINS_BY_OP = ${JSON.stringify(byOp, null, 2)};\n`;
await writeFile('build/app/js/skins.js', jsSkins);

// ── stage catalog ─────────────────────────────────────────────────
const chapterNames = {
  0: '序章', 1: '黑暗时代', 2: '异卵同生', 3: '二次呼吸', 4: '急性衰竭',
  5: '靶向药物', 6: '局部坏死', 7: '苦难摇篮', 8: '怒号光明', 9: '风暴瞭望',
  10: '破碎日冕', 11: '淬火尘霾', 12: '惊霆无声', 13: '恶兆湍流',
  14: '慈悲灯塔', 15: '离解复合', 16: '反常光谱', 17: '相变临界',
};
const materialByTier = {
  0: ['rock1', 'sugar1', 'ester1'],
  1: ['sugar1', 'ester1', 'iron1', 'ketone1'],
  2: ['device1', 'sugar2', 'ester2', 'iron1', 'device1'],
  3: ['alcohol', 'grindstone', 'rma', 'manganese', 'device2'],
  4: ['alloy', 'crystal', 'gel', 'manganese'],
};
function parseMain(title) {
  const m = title.match(/^((?:R8|M8|[0-9]{1,2})-[0-9]+[A-Za-z]?)\s*(.*)$/);
  if (!m) return null;
  const code = m[1];
  const chapterKey = code.startsWith('R8') || code.startsWith('M8') ? '8' : code.split('-')[0];
  if (!/^\d+$/.test(chapterKey)) return null;
  const chapter = Number(chapterKey);
  if (chapter < 0 || chapter > 17) return null;
  return { code, chapter, name: m[2] || code };
}
const mainRaw = stageTitles.main.map(parseMain).filter(Boolean);
const seen = new Set();
const main = [];
for (const s of mainRaw) {
  if (seen.has(s.code)) continue;
  seen.add(s.code);
  main.push(s);
}
main.sort((a, b) => a.chapter - b.chapter || a.code.localeCompare(b.code, 'zh', { numeric: true }));
const mainStages = main.map((s, i) => {
  const t = main.length <= 1 ? 0 : i / (main.length - 1);
  const rec = Math.round(4200 + (68000 - 4200) * Math.pow(t, 1.18));
  const drops = materialByTier[Math.min(4, Math.floor(t * 5))];
  const waves = t > 0.72 ? 5 : t > 0.35 ? 4 : 3;
  return {
    id: 'main-' + s.code, group: 'main', code: s.code,
    chapter: chapterNames[s.chapter] || `第${s.chapter}章`,
    chapterKey: s.chapter, name: s.name,
    rec, waves, desc: `${chapterNames[s.chapter] || '主线'} · ${s.name}。挂机清扫并回收战场物资。`,
    color: '#ffb544', drops,
    firstClearPrime: 1,
    rewards: { lmd: Math.round(420 + rec * 0.16), orundum: 12 + Math.round(t * 18), doctorExp: 10 + Math.round(t * 30), items: { [drops[0]]: 1 } },
  };
});

const annStages = stageTitles.annihilation.map((title, i) => {
  const n = stageTitles.annihilation.length;
  const t = n <= 1 ? 0 : i / (n - 1);
  const rec = Math.round(19000 + 51000 * Math.pow(t, 1.1));
  return {
    id: 'ann-' + (i + 1), group: 'annihilation', code: '剿灭', chapter: '长期剿灭', chapterKey: 900 + i,
    name: title, rec, waves: 5,
    desc: `${title} · 高压连续作战，单次奖励大量合成玉。`,
    color: '#ff7a59', drops: [materialByTier[4][i % 3], materialByTier[4][(i + 1) % 3]],
    firstClearPrime: 2,
    rewards: { lmd: Math.round(5000 + rec * 0.12), orundum: 160 + Math.round(t * 220), doctorExp: 30 + Math.round(t * 20), items: {} },
  };
});

const resources = OLD_STAGES.filter(s => s.group === 'resource' || s.group === 'chip').map(s => ({ ...s }));
const allStages = [...mainStages, ...resources, ...annStages];
const MIN_REC = 4200;
const MAX_REC = Math.max(...allStages.map(s => s.rec));
for (const s of mainStages) {
  const t = Math.max(0, Math.min(1, Number(s.chapterKey) / 15));
  s.idle = {
    orundumPerHour: 6000 + 12000 * t,
    shardsPerHour: 4.2 + 20 * t,
    blocksPerHour: 1.2 + 2 * t,
    lmdPerHour: 3000 + 9000 * t,
    expPerHour: 1200 + 4800 * t,
  };
}
for (const s of annStages) {
  const t = Math.max(0, Math.min(1, (s.rec - 19000) / 51000));
  s.idle = {
    orundumPerHour: 15000 + 3000 * t,
    shardsPerHour: 18 + 6 * t,
    blocksPerHour: 2.4 + 0.8 * t,
    lmdPerHour: 7000 + 3000 * t,
    expPerHour: 3000 + 1200 * t,
  };
}
for (const s of allStages) {
  if (!s.idle) {
    const t = Math.max(0, Math.min(1, (s.rec - MIN_REC) / (MAX_REC - MIN_REC)));
    s.idle = {
      orundumPerHour: 6000 + 12000 * t,
      shardsPerHour: 4.2 + 20 * t,
      blocksPerHour: 1.2 + 2 * t,
      lmdPerHour: 3000 + 9000 * t,
      expPerHour: 1200 + 4800 * t,
    };
  }
  s.firstClearPrime = s.firstClearPrime || (s.group === 'annihilation' ? 2 : 1);
}
const groups = [
  { id: 'main', name: '主线作战', desc: '推进全部主线章节。' },
  { id: 'resource', name: '资源筹备', desc: '龙门币与作战记录。' },
  { id: 'chip', name: '芯片搜索', desc: '定向获取精英化芯片。' },
  { id: 'annihilation', name: '长期剿灭', desc: '全部剿灭地图，产出大量合成玉。' },
];
const jsStages = `// Generated by tools/build-v2-data.mjs. ${allStages.length} stages.\nexport const STAGES = ${JSON.stringify(allStages, null, 2)};\nexport const STAGE_GROUPS = ${JSON.stringify(groups, null, 2)};\nexport const MAIN_CHAPTERS = ${JSON.stringify([...new Map(mainStages.map(s => [s.chapterKey, { key: s.chapterKey, chapter: s.chapter, name: s.chapter }])).values()], null, 2)};\n`;
await writeFile('build/app/js/stages-v2.js', jsStages);

