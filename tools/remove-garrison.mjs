import fs from 'node:fs';
import { OPERATORS, STARTERS, LIMITED_IDS } from '../build/app/js/operators.js';
import { SPINE38_OPERATORS, SPINE35_ONLY } from '../build/app/js/spine38-index.js';

const removed = OPERATORS.filter(o => /卫戍协议/.test(o.name)).map(o => o.id);
const removedSet = new Set(removed);
const ops = OPERATORS.filter(o => !removedSet.has(o.id));
const spine38 = Object.fromEntries(Object.entries(SPINE38_OPERATORS).filter(([id]) => !removedSet.has(id)));
const spine35 = Object.fromEntries(Object.entries(SPINE35_ONLY).filter(([id]) => !removedSet.has(id)));
const limited = LIMITED_IDS.filter(id => !removedSet.has(id));

fs.writeFileSync('build/app/js/operators.js',
  `// Generated by tools/build-v2-data.mjs. ${ops.length} operators.\nexport const OPERATORS = ${JSON.stringify(ops, null, 2)};\n\nexport const STARTERS = ${JSON.stringify(STARTERS)};\nexport const LIMITED_IDS = ${JSON.stringify(limited)};\n`);
fs.writeFileSync('build/app/js/spine38-index.js',
  `// Generated Spine index. 卫戍协议 operators removed.\nexport const SPINE38_OPERATORS = ${JSON.stringify(spine38, null, 2)};\n\nexport const SPINE35_ONLY = ${JSON.stringify(spine35, null, 2)};\n`);

console.log(JSON.stringify({ removed, operators: ops.length, spine38: Object.keys(spine38).length, spine35: Object.keys(spine35).length }, null, 2));
