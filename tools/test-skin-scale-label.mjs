import { connect, evalJS, screenshot } from './cdp.mjs';
const { send } = await connect();
await send('Page.bringToFront');
await send('Runtime.enable'); await send('Network.enable'); await send('Network.setCacheDisabled',{cacheDisabled:true});
await send('Page.navigate',{url:'http://127.0.0.1:8765/index.html?v=scalelabel'});
await new Promise(r=>setTimeout(r,1200));
await send('Runtime.evaluate',{expression:`document.getElementById('enterBtn')?.click()`,userGesture:true});
await new Promise(r=>setTimeout(r,1500));
await send('Runtime.evaluate',{expression:`document.querySelector('[data-action="tutorial-skip"]')?.click()`,userGesture:true});
await new Promise(r=>setTimeout(r,500));
await evalJS(send, `__RHODES__.setView('skins',true); true`);
await new Promise(r=>setTimeout(r,700));
console.log(await evalJS(send, `JSON.stringify({labels:document.querySelectorAll('.skin-scale-row label').length,text:document.querySelector('.skin-scale-row label')?.textContent,sliders:document.querySelectorAll('[data-skin-scale]').length,resets:document.querySelectorAll('[data-action="reset-skin-scale"]').length})`));
