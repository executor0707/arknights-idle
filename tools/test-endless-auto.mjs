import { connect, evalJS, screenshot } from './cdp.mjs';
const { send } = await connect();
await send('Page.bringToFront');
await send('Runtime.enable'); await send('Network.enable'); await send('Network.setCacheDisabled',{cacheDisabled:true});
await send('Page.navigate',{url:'http://127.0.0.1:8765/index.html?v=endlessauto'});
await new Promise(r=>setTimeout(r,1200));
await send('Runtime.evaluate',{expression:`localStorage.clear();location.reload()`,userGesture:true});
await new Promise(r=>setTimeout(r,1200));
await send('Runtime.evaluate',{expression:`document.getElementById('enterBtn')?.click()`,userGesture:true});
await new Promise(r=>setTimeout(r,1500));
await send('Runtime.evaluate',{expression:`document.querySelector('[data-action="tutorial-skip"]')?.click()`,userGesture:true});
await new Promise(r=>setTimeout(r,500));
await evalJS(send,`document.querySelector('[data-action="stage-group"][data-group="endless"]')?.click();true`);
await new Promise(r=>setTimeout(r,800));
console.log('before', await evalJS(send,`JSON.stringify({selected:__RHODES__.state.stage.selected,group:__RHODES__.battle.stage.group,name:__RHODES__.battle.stage.name,auto:__RHODES__.state.stage.auto})`));
await evalJS(send,`__RHODES__.battle._finish(true,'test');true`);
await new Promise(r=>setTimeout(r,4200));
console.log('after', await evalJS(send,`JSON.stringify({selected:__RHODES__.state.stage.selected,group:__RHODES__.battle.stage.group,name:__RHODES__.battle.stage.name,next:__RHODES__.battle.nextStageId,endless:__RHODES__.G.STAGES.filter(s=>s.group==='endless').map(s=>s.name)})`));
await screenshot(send,'.cache/endless-auto-next.png',1440,1000);
process.exit(0);
