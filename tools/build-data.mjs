import { writeFile, mkdir } from 'node:fs/promises';
import { OPERATORS, STARTERS, LIMITED_IDS } from './operators.mjs';

const data = OPERATORS.map(o => ({
  ...o,
  img: `assets/operators/${o.id}.webp`,
  role: { 先锋: 'vanguard', 近卫: 'guard', 重装: 'defender', 狙击: 'sniper', 术师: 'caster', 医疗: 'medic', 辅助: 'supporter', 特种: 'specialist' }[o.cls],
}));

await mkdir('build/app/js', { recursive: true });
const js = `// Generated by tools/build-data.mjs — do not edit by hand.\nexport const OPERATORS = ${JSON.stringify(data, null, 2)};\n\nexport const STARTERS = ${JSON.stringify(STARTERS)};\nexport const LIMITED_IDS = ${JSON.stringify(LIMITED_IDS)};\n`;
await writeFile('build/app/js/operators.js', js);
console.log('Wrote', data.length, 'operators');
