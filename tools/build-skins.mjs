import { readFile, writeFile } from 'node:fs/promises';

const raw = JSON.parse(await readFile('.cache/skins.json', 'utf8'));
const skins = [];
for (const op of raw) {
  for (const s of op.skins) {
    skins.push({
      id: `${op.id}-${s.key}`,
      opId: op.id,
      key: s.key,
      name: s.name,
      series: s.series,
      color: s.color,
      desc: s.desc,
      img: `assets/skins/${op.id}-${s.key}.webp`,
      price: 88,
    });
  }
}
const byOp = {};
for (const s of skins) (byOp[s.opId] ||= []).push(s);
const js = `// Generated by tools/build-skins.mjs — 皮肤资料来自 PRTS Wiki。\nexport const SKINS = ${JSON.stringify(skins, null, 2)};\nexport const SKIN_BY_ID = new Map(SKINS.map(s => [s.id, s]));\nexport const SKINS_BY_OP = ${JSON.stringify(byOp, null, 2)};\n`;
await writeFile('build/app/js/skins.js', js);
console.log('skins', skins.length);
